from django.contrib.auth import get_user_model
from django.test import TestCase, override_settings
from django.utils import timezone

from .models import BlogAuthor, BlogCategory, BlogPost, BlogTag

User = get_user_model()


@override_settings(ALLOWED_HOSTS=["*"])
class BlogPublicViewTests(TestCase):
    def setUp(self):
        self.category = BlogCategory.objects.create(name="Guides")
        self.tag = BlogTag.objects.create(name="seo")
        self.author = BlogAuthor.objects.create(name="Asha", role="Founder", bio="Builds stores.")
        self.post = BlogPost.objects.create(
            title="How to launch a store in a day",
            excerpt="A short guide.",
            body="<p>Some <script>alert(1)</script>content.</p>",
            category=self.category,
            author=self.author,
            is_published=True,
        )
        self.post.tags.add(self.tag)
        self.draft = BlogPost.objects.create(title="Unpublished draft", is_published=False)

    def test_slug_autogenerated(self):
        self.assertEqual(self.post.slug, "how-to-launch-a-store-in-a-day")

    def test_body_sanitized_on_save(self):
        self.assertNotIn("<script>", self.post.body)
        self.assertIn("Some", self.post.body)

    def test_index_lists_published_only(self):
        resp = self.client.get("/blog/", HTTP_HOST="mnxstore.test")
        self.assertEqual(resp.status_code, 200)
        self.assertContains(resp, self.post.title)
        self.assertNotContains(resp, self.draft.title)

    def test_detail_200_with_jsonld(self):
        resp = self.client.get(f"/blog/{self.post.slug}/", HTTP_HOST="mnxstore.test")
        self.assertEqual(resp.status_code, 200)
        self.assertContains(resp, "BlogPosting")
        self.assertContains(resp, self.author.name)

    def test_draft_detail_404(self):
        resp = self.client.get(f"/blog/{self.draft.slug}/", HTTP_HOST="mnxstore.test")
        self.assertEqual(resp.status_code, 404)

    def test_category_and_tag_pages(self):
        resp = self.client.get(f"/blog/category/{self.category.slug}/", HTTP_HOST="mnxstore.test")
        self.assertContains(resp, self.post.title)
        resp = self.client.get(f"/blog/tag/{self.tag.slug}/", HTTP_HOST="mnxstore.test")
        self.assertContains(resp, self.post.title)

    @override_settings(ALLOWED_HOSTS=["*"], PLATFORM_HOSTS=["mnxstore.test"])
    def test_sitemap_includes_published_post(self):
        resp = self.client.get("/sitemap.xml", HTTP_HOST="mnxstore.test")
        self.assertEqual(resp.status_code, 200)
        self.assertIn(f"/blog/{self.post.slug}/".encode(), resp.content)
        self.assertNotIn(self.draft.slug.encode() if self.draft.slug else b"__none__", resp.content)

    def test_tenant_host_serves_storefront_not_blog(self):
        # A host bound to a store (primary_domain or verified Domain) is
        # swapped by StorefrontHostMiddleware to config.storefront_urls before
        # routing even reaches apps.blog.urls — a real 404, not a redirect
        # (the view's own "if request.project: redirect('/app/')" guard, same
        # as apps.core.views.pricing/legal_page, covers a different case: an
        # apex-host request where request.project still resolves via the
        # logged-in user's own store membership).
        from apps.projects.models import Project

        Project.objects.create(name="Acme", primary_domain="acme.test")
        resp = self.client.get("/blog/", HTTP_HOST="acme.test")
        self.assertEqual(resp.status_code, 404)


class BlogControlAccessTests(TestCase):
    def setUp(self):
        self.admin = User.objects.create_superuser("admin", "admin@example.com", "pw12345!")
        self.staff = User.objects.create_user("staff", "staff@example.com", "pw12345!", is_staff=True)

    def test_superuser_can_list(self):
        self.client.force_login(self.admin)
        resp = self.client.get("/admin/blog/")
        self.assertEqual(resp.status_code, 200)

    def test_plain_staff_denied(self):
        self.client.force_login(self.staff)
        resp = self.client.get("/admin/blog/")
        self.assertEqual(resp.status_code, 403)

    def test_create_post_via_form(self):
        self.client.force_login(self.admin)
        resp = self.client.post("/admin/blog/new/", {
            "title": "New post", "excerpt": "e", "body": "<p>b</p>",
            "category": "", "tags": [], "author": "",
            "seo_title": "", "seo_description": "", "is_published": "on",
        })
        self.assertEqual(resp.status_code, 302)
        post = BlogPost.objects.get(title="New post")
        self.assertTrue(post.is_published)
        self.assertIsNotNone(post.published_at)
